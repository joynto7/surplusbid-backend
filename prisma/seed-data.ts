export interface SeedLot {
  key: string;
  seller: string;
  category: string;
  title: string;
  description: string;
  condition: string;
  quantity: number;
  location: string;
  specs: [string, string][];
  startingPrice: number;
  reserve: number;
  increment: number;
  images: string[];
  status: 'LIVE' | 'SOLD' | 'UNSOLD' | 'DRAFT';
  /** LIVE: hours from now until the close. DRAFT: hours until it would open. */
  endsInHours?: number;
  /** SOLD / UNSOLD: days since the close. */
  endedDaysAgo?: number;
  durationDays: number;
  bids: number;
  /** SOLD: final price as a multiple of the starting price. */
  finalMultiplier?: number;
  /** SOLD: the winning buyer's key. */
  winner?: string;
  /** LIVE: the demo buyer bid here and has been outbid, so "Re-bid" shows in their dashboard. */
  demoBuyerOutbid?: boolean;
}

